export function createScanwordLevelState(id: ScanwordLevelId) {
  const info = SCANWORD_LEVELS.find((level) => level.id === id)!;
  const puzzle = SCANWORD_PUZZLES.find((level) => level.id === id)!;
  return createStudyState(
    puzzle.words.map((word, i) => ({
      id: `${id}-${i}`,
      term: word.answer,
      definition: word.clue,
      revision: info.revision,
    })),
    'scanword',
    {
      direction: 'reverse',
      count: info.wordCount,
      shuffle: false,
      answerType: 'written',
      filter: 'all',
    },
    () => 0,
    {
      rows: puzzle.rows,
      columns: puzzle.columns,
      words: puzzle.words.map((word) => ({
        row: word.row,
        column: word.column,
        direction: word.direction,
      })),
    },
  );
}
